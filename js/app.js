let currentLang = localStorage.getItem("portfolio-lang") || "es";

function updateLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("portfolio-lang", lang);

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.getAttribute("data-i18n");
    if (translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.getAttribute("data-i18n-placeholder");
    if (translations[lang][key]) {
      element.setAttribute("placeholder", translations[lang][key]);
    }
  });

  const btnEs = document.getElementById("lang-btn-es");
  const btnEn = document.getElementById("lang-btn-en");
  if (btnEs && btnEn) {
    if (lang === "es") {
      btnEs.classList.add("active");
      btnEn.classList.remove("active");
    } else {
      btnEn.classList.add("active");
      btnEs.classList.remove("active");
    }
  }
}

document.addEventListener("DOMContentLoaded", () => {
  updateLanguage(currentLang);

  const btnEs = document.getElementById("lang-btn-es");
  const btnEn = document.getElementById("lang-btn-en");

  if (btnEs) {
    btnEs.addEventListener("click", () => updateLanguage("es"));
  }
  if (btnEn) {
    btnEn.addEventListener("click", () => updateLanguage("en"));
  }

  const form = document.getElementById("contactForm");
  if (form) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      
      const nameInput = document.getElementById("nameInput");
      const emailInput = document.getElementById("emailInput");
      const phoneInput = document.getElementById("phoneInput");
      const messageInput = document.getElementById("messageInput");

      let isValid = true;

      const nameVal = nameInput.value.trim();
      const nameRegex = /^[a-zA-ZÀ-ÿ\s]{3,}$/;
      if (!nameRegex.test(nameVal)) {
        nameInput.classList.add("is-invalid");
        nameInput.classList.remove("is-valid");
        isValid = false;
      } else {
        nameInput.classList.remove("is-invalid");
        nameInput.classList.add("is-valid");
      }

      const emailVal = emailInput.value.trim();
      const emailFeedback = emailInput.nextElementSibling;
      let emailErrKey = "";

      if (!emailVal.includes("@")) {
        emailErrKey = "val.email_missing_at";
      } else {
        const parts = emailVal.split("@");
        const domain = parts[1] || "";
        if (!domain.includes(".")) {
          emailErrKey = "val.email_missing_dot";
        } else {
          const popularDomains = [
            "gmail.com", "hotmail.com", "outlook.com", "yahoo.com", "icloud.com",
            "protonmail.com", "proton.me", "zoho.com", "live.com", "live.com.mx", "yahoo.com.mx"
          ];
          const tempDomains = [
            "yopmail.com", "mailinator.com", "10minutemail.com", "tempmail.com",
            "guerrillamail.com", "sharklasers.com", "dispostable.com", "getairmail.com"
          ];
          const isPopular = popularDomains.includes(domain.toLowerCase());
          const isTemp = tempDomains.some(d => domain.toLowerCase().endsWith(d));
          const secureTlds = [".com", ".org", ".net", ".edu", ".edu.mx", ".gob", ".gob.mx", ".mx", ".co", ".io", ".tech", ".dev"];
          const hasSecureTld = secureTlds.some(tld => domain.toLowerCase().endsWith(tld));
          const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
          if (isTemp || (!isPopular && !hasSecureTld) || !emailRegex.test(emailVal)) {
            emailErrKey = "val.email_invalid_domain";
          }
        }
      }

      if (emailErrKey) {
        emailInput.classList.add("is-invalid");
        emailInput.classList.remove("is-valid");
        emailFeedback.setAttribute("data-i18n", emailErrKey);
        emailFeedback.textContent = translations[currentLang][emailErrKey];
        isValid = false;
      } else {
        emailInput.classList.remove("is-invalid");
        emailInput.classList.add("is-valid");
      }

      const phoneVal = phoneInput.value.trim();
      const phoneRegex = /^[+]?[0-9\s.\-()]+$/;
      const cleanedPhone = phoneVal.replace(/\D/g, "");
      const isRepetitive = /^(.)\1+$/.test(cleanedPhone);
      if (!phoneRegex.test(phoneVal) || cleanedPhone.length < 8 || cleanedPhone.length > 15 || isRepetitive) {
        phoneInput.classList.add("is-invalid");
        phoneInput.classList.remove("is-valid");
        isValid = false;
      } else {
        phoneInput.classList.remove("is-invalid");
        phoneInput.classList.add("is-valid");
      }

      const messageVal = messageInput.value.trim();
      if (messageVal.length < 30 || messageVal.length > 500) {
        messageInput.classList.add("is-invalid");
        messageInput.classList.remove("is-valid");
        isValid = false;
      } else {
        messageInput.classList.remove("is-invalid");
        messageInput.classList.add("is-valid");
      }

      if (isValid) {
        alert(currentLang === "es" ? "¡Mensaje enviado con éxito!" : "Message sent successfully!");
        form.reset();
        nameInput.classList.remove("is-valid");
        emailInput.classList.remove("is-valid");
        phoneInput.classList.remove("is-valid");
        messageInput.classList.remove("is-valid");
      }
    });
  }
});
